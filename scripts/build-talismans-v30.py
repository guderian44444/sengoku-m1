"""Build the runtime catalog and design table from the same 30 charm definitions."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LABELS = {'damage_bonus': ('基準攻擊', '+%d'), 'move_bonus': ('移動', '+%.0f%%'),
    'reach_bonus': ('範圍', '+%d'), 'attack_speed_bonus': ('攻速', '+%.0f%%'),
    'knockback_bonus': ('擊退', '+%.1f'), 'heavy_bonus': ('重手傷害', '+%.0f%%'),
    'charged_bonus': ('蓄力傷害', '+%.0f%%'), 'air_bonus': ('空中傷害', '+%.0f%%'),
    'throw_bonus': ('投摔傷害', '+%.0f%%'), 'special_bonus': ('必殺傷害', '+%.0f%%'),
    'food_bonus': ('食物回復', '+%.0f%%'), 'kill_rage': ('擊殺怒氣', '+%d'),
    'guard_rage': ('成功防禦怒氣', '+%d'), 'burn_resist': ('燃燒時間', '-%.0f%%'),
    'freeze_resist': ('冰凍時間', '-%.0f%%'), 'poison_resist': ('中毒時間', '-%.0f%%')}

def build():
    data = json.loads((ROOT/'game/data/talismans-v30.json').read_text(encoding='utf-8'))
    assert len(data['items']) == 30
    catalog = {}
    doc = ['# v0.30 三十種護符\n', '名稱、組合與數值是遊戲創作；史料只支持信仰題材，不證明現實能力或戰國時代有同名商品。\n',
        '一次只裝備一件。定值護盾用盡消失；百分比減傷依剩餘耐久衰減，剩 20% 耐久損壞。其他加成在護符完好期間固定有效。所有護符沿用相同存檔與出售規則。\n',
        '新增款以初始減傷 6–18%、攻速最多 +6%、移動最多 +10%、條件傷害最多 +12% 為上限。高階款有二至三項小加成，不能疊戴。原有六款保留既有數值與 ID。\n',
        '| 護符 | 階位 | 功能定義 | 說明 | 耐久 | 題材 |\n| --- | --- | --- | --- | --- | --- |']
    for item in data['items']:
        assert item['id'] not in catalog and item['source'] in data['sources']
        assert 0 < item['durability'] <= 320 and len(item['icons']) <= 3
        effects = item.get('effects',{})
        assert all(key in LABELS for key in effects)
        assert effects.get('attack_speed_bonus',0) <= .06 and effects.get('move_bonus',0) <= .10
        assert all(effects.get(key,0) <= .12 for key in ['heavy_bonus','charged_bonus','air_bonus','throw_bonus','special_bonus'])
        source = data['sources'][item['source']]
        functions = ['吸收共 %d 點傷害' % item['durability']] if item['mode'] == 'fixed' else ['初始減傷 %.0f%%' % (item['reduction']*100)]
        for key, value in effects.items():
            label, pattern = LABELS[key]
            functions.append(label + ' ' + (pattern % (value*100 if '%%' in pattern else value)))
        row = {'name': item['name'], 'mode': item['mode'], 'durability': item['durability'],
            'reduction': item.get('reduction',0), 'damage_bonus':0, 'move_bonus':0.0, 'reach_bonus':0.0,
            'price':item['price'], 'tier':item['tier'], 'image':item['image'], 'color':item['color'],
            'icons':item['icons'], 'history':source['note'], 'source':source['url'], **effects}
        row['description'] = '；'.join(functions) + '。' + item['flavor'] + '\n' + ('容量用盡消失。' if item['mode']=='fixed' else '減傷率隨耐久比例降低，剩 20% 耐久損壞。') + '\n題材：' + source['note'] + '\n名稱與數值為遊戲創作。'
        catalog[item['id']] = row
        doc.append('| %s | %s | %s | %s | %d | [%s](%s) |' % (item['name'],item['tier'],'；'.join(functions),item['flavor'],item['durability'],source['title'],source['url']))
    doc += ['\n## 功能結算\n', '重手含 heavy／dash_heavy／upper_heavy／ground_slam；蓄力含 charged／charged_upper／charged_slam；空中含 air_light／air_heavy。條件傷害只增強該次直接命中，不增強後續燃燒、中毒或環境傷害。必殺加成只對 special 的直接命中。成功防禦怒氣每次真的擋住一擊才給；擊殺怒氣每個敵人只給一次。食物加成按實際可回復生命封頂。抗性縮短新施加的異常時間，不給免疫。\n',
        '掉落：原關卡六款固定藏寶保留；雜兵／小王／大王另外以 2%／8%／18% 擲護符掉落，第一關最高三階、第二關最高四階。護符與武器掉落各自擲骰；行囊滿時保留地上物品。\n',
        '頭上顯示最多三枚小型半透明功能符號，與當前人物圖像上緣保留空隙。卸下、損壞或死亡後消失。\n']
    runtime = 'extends RefCounted\n\n# Generated by scripts/build-talismans-v30.py.\nconst ITEMS := {\n' + '\n'.join('\t'+json.dumps(key)+':'+json.dumps(row,ensure_ascii=False)+',' for key,row in catalog.items()) + '\n}\n'
    return {ROOT/'game/core/talisman_catalog.gd': runtime, ROOT/'docs/TALISMANS-V30.md': '\n'.join(doc).rstrip()+'\n'}

if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    for path, content in build().items():
        if args.check: assert path.read_text(encoding='utf-8')==content,str(path)+' has drifted'
        else: path.write_text(content,encoding='utf-8')
    print('TALISMAN CATALOG PASS: 30 definitions, balanced bounds and matching runtime/documentation')
