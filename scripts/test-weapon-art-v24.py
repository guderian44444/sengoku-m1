#!/usr/bin/env python3
"""Source provenance, 48-item registration and immutable-approved-art checks."""
from pathlib import Path
import json,hashlib,re,os,sys
from oichi_skirt_v26 import approved_expected_hash,asset_path
import numpy as np
from PIL import Image

ROOT=Path(__file__).resolve().parents[1];DATA=ROOT/'game/assets/v24/weapons';OUT=ROOT/'game/assets/v22/weapons'
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
reg=json.loads((OUT/'registration.json').read_text())
old=json.loads((DATA/'registration-18-before.json').read_text())
research=json.loads((DATA/'research-30.json').read_text())['weapons']
arts=json.loads((DATA/'art-spec30.json').read_text())['items']
ency=json.loads((OUT/'encyclopedia.json').read_text());oldency=json.loads((DATA/'encyclopedia-18-before.json').read_text())
assert len(reg['items'])==48 and len(arts)==len(research)==30
assert set(reg['items'])==set(old['items'])|{x['id'] for x in research}==set(ency)
assert all(reg['items'][id]==s for id,s in old['items'].items()),'Original 18 registration records changed'
assert all(reg['sources'][id]==s and sha(OUT/s['file'])==s['sha256'] for id,s in old['sources'].items()),'Approved original source images changed'
assert all(ency[id]==s for id,s in oldency.items()),'Original 18 historical records changed'
catalog=(ROOT/'game/core/weapon_catalog.gd').read_text();oldcatalog=(DATA/'catalog-18-before.txt').read_text()
oldlines=re.findall(r'^\s*"[^"]+":\{"name":.+$',oldcatalog,re.M)
assert len(oldlines)==18 and all(line in catalog for line in oldlines),'Original catalog item changed'
protected=json.loads((DATA/'protected-before.json').read_text());protected.update(json.loads((DATA/'characters-protected-before.json').read_text())['files'])
# v25 is a separately reviewed, armor-only overlay. Retain the historical v24
# snapshot and allow only exact old->new hashes recorded by that correction.
overlay=ROOT/'game/assets/v25/nobunaga-dark-red.json'
if overlay.exists():
 for p,change in json.loads(overlay.read_text())['approved_overlay'].items():
  assert p in protected and protected[p]==change['before_sha256'],('Invalid v25 base',p)
  protected[p]=change['after_sha256']
verified_protected=0
for p,digest in protected.items():
 if '--assets-only' in sys.argv and not asset_path(p):continue
 assert sha(ROOT/p)==approved_expected_hash(p,digest),p+' approved bytes changed'
 verified_protected+=1
# v26 source/mask reconstruction is separately verified by oichi_skirt_v26.py --check.
# Historical v24/v25 baselines remain immutable; only an exact recorded hash transition is accepted.
counts={family:sum(x['family']==family for x in research) for family in ['sword','spear','bow']};assert set(counts.values())=={10}
report=[];silhouettes={}
for art in arts:
 id=art['id'];spec=reg['items'][id];raw=ROOT/art['raw_source'];prepared=OUT/reg['sources'][id]['file'];sprite=OUT/spec['file']
 a=np.array(Image.open(raw).convert('RGBA'));b=np.array(Image.open(prepared).convert('RGBA'))
 assert sha(raw)==art['source_sha256'],id+' raw generated bytes changed'
 assert a.shape==b.shape and np.array_equal(a[:,:,:3],b[:,:,:3]),id+' RGB was altered'
 assert np.all(b[:,:,3]<=a[:,:,3]),id+' opacity unexpectedly added'
 assert b[:,:,3].max()>=250 and int((b[:,:,3]>0).sum())>600
 crop=Image.open(prepared).crop(spec['rect']);actual=Image.open(sprite)
 assert actual.tobytes()==crop.tobytes(),id+' crop differs from prepared source'
 assert sha(sprite)==spec['sha256'] and spec['length']>=600
 for key in ['grip','tip_top','tip_bottom']:
  x,y=spec[key];assert actual.getpixel((x,y))[3]>128,(id,key)
 alpha=actual.getchannel('A');mask=alpha.point(lambda p:255 if p>=128 else 0)
 bbox=mask.getbbox();shape=mask.crop(bbox);shape.thumbnail((128,256),Image.Resampling.NEAREST)
 normalized=Image.new('L',(128,256));normalized.paste(shape,((128-shape.width)//2,(256-shape.height)//2))
 digest=hashlib.sha256(normalized.tobytes()).hexdigest();assert digest not in silhouettes,(id,silhouettes.get(digest),'identical monochrome silhouette')
 silhouettes[digest]=id
 if id.startswith('bow'):
  fraction=(spec['grip'][1]-spec['tip_top'][1])/spec['length']
  assert .57<=fraction<=.70 and 160<=spec['world_length']<=180,(id,'approved bow proportion')
 assert ency[id]['reference_images']==[] and '授權' in ency[id]['photo_status']
 report.append({'id':id,'source_sha256':sha(raw),'prepared_sha256':sha(prepared),'sprite_sha256':sha(sprite),'rgb_unchanged':True,'removed_alpha_pixels':int(np.count_nonzero(a[:,:,3]!=b[:,:,3])),'silhouette_sha256':digest,'grip':spec['grip'],'world_length':spec['world_length'],'visible_native_length':spec['length']})
clips=frames=0
for h in ['nobunaga','tadakatsu','oichi']:
 r=json.loads((ROOT/f'game/assets/v22/{h}/registration.json').read_text());clips+=len(r['clips']);frames+=sum(len(c['frames']) for c in r['clips'].values())
assert clips==77 and frames==462
result={'status':'PASS','catalog_count':48,'new_by_family':counts,'approved_original_weapons':18,'protected_file_count':verified_protected,'code_snapshot_checked':'--assets-only' not in sys.argv,'protected_hero_clips':clips,'protected_hero_frames':frames,'raw_originals_preserved':True,'alpha_processing_explicit':True,'identical_normalized_silhouettes':0,'visual_review_required':'Distinct silhouette hashes supplement, but never replace, the item-by-item visual review and all-action composites.','items':report}
dest=Path(os.environ.get('TEST_ARTIFACT_DIR',str(ROOT/'artifacts/weapon-expansion-v24')));dest.mkdir(exist_ok=True,parents=True);(dest/'art-validation.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
print(f'WEAPON ART V24 PASS: 48 catalog items, 30 original sources, {verified_protected} immutable files, 77 clips / 462 hero frames, 18 approved weapons unchanged')
